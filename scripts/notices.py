#!/usr/bin/env python3
"""Renders THIRD_PARTY_NOTICES.md from `cargo about generate --format json` (stdin)."""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OWN = {"plassi", "plassi-typeset"}
# Licences whose text carries no per-crate copyright line: one copy is enough.
ONE_TEXT = {"Apache-2.0", "MPL-2.0", "BSL-1.0", "CC0-1.0", "Unicode-3.0", "OFL-1.1", "Ubuntu-font-1.0"}


def norm(text):
    return re.sub(r"\s+", " ", text).strip()


def block(text):
    return "```text\n" + text.strip("\n").replace("```", "'''") + "\n```\n"


def fonts(crate_dirs):
    out = ["## Fonts\n"]
    own = ROOT / "typeset" / "fonts"
    out.append("### Source Sans 3 and Source Serif Pro (SIL Open Font License 1.1)\n")
    out.append("The interface font and the fonts of the printed PDFs.\n")
    for name in ["LICENSE-SourceSans3.md", "LICENSE-SourceSerifPro.md"]:
        out.append(block((own / name).read_text()))
    egui = crate_dirs.get("epaint_default_fonts")
    if egui:
        out.append("### egui's fallback fonts (from epaint_default_fonts)\n")
        out.append("Ubuntu Light, Hack, Noto Emoji and emoji-icon-font, used for characters Source Sans 3 lacks.\n")
        for title, name in [("Ubuntu Light: Ubuntu Font Licence 1.0", "UFL.txt"),
                            ("Hack", "Hack-Regular.txt"),
                            ("Noto Emoji: SIL Open Font License 1.1", "OFL.txt"),
                            ("emoji-icon-font: MIT", "emoji-icon-font-mit-license.txt")]:
            out.append(f"#### {title}\n")
            out.append(block((egui / "fonts" / name).read_text(errors="replace")))
    return out


def main():
    data = json.load(sys.stdin)
    crate_dirs = {c["package"]["name"]: pathlib.Path(c["package"]["manifest_path"]).parent
                  for c in data["crates"]}
    groups = {}
    for lic in data["licenses"]:
        users = sorted({(u["crate"]["name"], u["crate"]["version"]) for u in lic["used_by"]})
        users = [u for u in users if u[0] not in OWN]
        if not users:
            continue
        g = groups.setdefault(lic["id"], {"name": lic["name"], "crates": set(), "texts": []})
        g["crates"].update(users)
        if lic["id"] in ONE_TEXT and g["texts"]:
            continue
        if norm(lic["text"]) not in {norm(t) for t in g["texts"]}:
            g["texts"].append(lic["text"])
    order = sorted(groups.items(), key=lambda kv: (-len(kv[1]["crates"]), kv[0]))

    out = ["# Third-party software in Plassi\n",
           "Plassi is © 2026 Niklas Iivari. All rights reserved. The desktop app and the browser "
           "version include the open-source software and fonts below, used under their licences. "
           "Each licence lists the Rust crates it covers, followed by its text.\n",
           "Generated by scripts/notices.sh from Cargo.lock; do not edit by hand.\n"]
    out += fonts(crate_dirs)
    for spdx, g in order:
        out.append(f"## {g['name'].replace('&quot;', '\"')} ({spdx})\n")
        out.append(", ".join(f"{n} {v}" for n, v in sorted(g["crates"])) + "\n")
        for text in g["texts"]:
            out.append(block(text))
    notices = []
    for name, version in sorted({(c["package"]["name"], c["package"]["version"]) for c in data["crates"]}):
        if name in OWN:
            continue
        for f in sorted(crate_dirs[name].glob("NOTICE*")):
            notices.append(f"### {name} {version}: {f.name}\n")
            notices.append(block(f.read_text(errors="replace")))
    if notices:
        out.append("## Additional notices\n")
        out.append("NOTICE files shipped with the crates above.\n")
        out += notices
    sys.stdout.write("\n".join(out))


main()
